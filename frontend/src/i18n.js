export function translate(text, language = "English") {
    if (typeof text !== "string" || language === "English") return text;
    const localized = translations[language]?.[text];
    if (localized) return localized;

    const greeting = text.match(/^(Good morning|Welcome), (.+?)(!)?$/);
    if (greeting) {
        const template = translations[language]?.[`${greeting[1]}, {name}${greeting[3] || ""}`];
        if (template) return template.replace("{name}", greeting[2]);
    }

    return text;
}
